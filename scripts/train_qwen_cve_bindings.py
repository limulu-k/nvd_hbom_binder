SYSTEM_PROMPT = """You extract affected software bindings from an NVD CVE description.
Return exactly one minified JSON object with the single top-level key \"bindings\". Do not add Markdown or explanations.

Each binding has this exact shape:
{"vendor":string|null,"product":string,"version_ranges":[{"start":string|null,"start_inclusive":boolean|null,"end":string|null,"end_inclusive":boolean|null}]}

Rules:
- Extract only bindings supported by the description; never invent a vendor, product, or version.
- Preserve the naming and normalization style represented by the training labels.
- An exact version uses the same start and end with both inclusive flags true.
- "before/prior to VERSION" has an exclusive end; "through/up to VERSION" has an inclusive end.
- A plain "PRODUCT VERSION" mention is exact unless an explicit range modifier applies.
- Versions joined only by commas, "and", or "or" are separate exact versions, not a continuous interval.
- A missing endpoint and its inclusive flag are both null.
- If a product is affected but no version is stated, include one range whose four values are null.
- Rejected, reserved, or otherwise non-vulnerability records have an empty bindings array.
- Keep multiple products and multiple disjoint version ranges separate as represented by the text."""


class DataValidationError(ValueError):
    """Raised when the merged supervision JSONL cannot be trained safely."""


@dataclass(frozen=True)
class VersionRange:
    start: str | None
    start_inclusive: bool | None
    end: str | None
    end_inclusive: bool | None


@dataclass(frozen=True)
class Binding:
    vendor: str | None
    product: str
    version_ranges: tuple[VersionRange, ...]


@dataclass(frozen=True)
class TrainingRecord:
    cve_id: str
    description: str
    bindings: tuple[Binding, ...]


@dataclass(frozen=True)
class CVFold:
    index: int
    train_records: tuple[TrainingRecord, ...]
    validation_records: tuple[TrainingRecord, ...]
    metadata: dict[str, Any]


class EncodedDataset:
    """Small map-style dataset accepted directly by Transformers Trainer."""

    def __init__(self, examples: list[dict[str, list[int]]]) -> None:
        self.examples = examples

    def __len__(self) -> int:
        return len(self.examples)

    def __getitem__(self, index: int) -> dict[str, list[int]]:
        return self.examples[index]


def _nullable_string(value: Any, field: str, line_no: int) -> str | None:
    if value is None:
        return None
    if not isinstance(value, str) or not value.strip():
        raise DataValidationError(f"{line_no}행 {field}: null 또는 비어 있지 않은 문자열이어야 합니다.")
    return value.strip()


def _nullable_bool(value: Any, field: str, line_no: int) -> bool | None:
    if value is None or isinstance(value, bool):
        return value
    raise DataValidationError(f"{line_no}행 {field}: boolean 또는 null이어야 합니다.")


def _normalize_version_range(value: Any, line_no: int, prefix: str) -> VersionRange:
    if not isinstance(value, dict):
        raise DataValidationError(f"{line_no}행 {prefix}: object여야 합니다.")
    required = {"start", "start_inclusive", "end", "end_inclusive"}
    missing = required.difference(value)
    if missing:
        raise DataValidationError(f"{line_no}행 {prefix}: 필수 키 누락 {sorted(missing)}")

    start = _nullable_string(value["start"], f"{prefix}.start", line_no)
    end = _nullable_string(value["end"], f"{prefix}.end", line_no)
    start_inclusive = _nullable_bool(
        value["start_inclusive"], f"{prefix}.start_inclusive", line_no
    )
    end_inclusive = _nullable_bool(
        value["end_inclusive"], f"{prefix}.end_inclusive", line_no
    )
    if (start is None) != (start_inclusive is None):
        raise DataValidationError(
            f"{line_no}행 {prefix}: start와 start_inclusive는 함께 null이거나 함께 값이 있어야 합니다."
        )
    if (end is None) != (end_inclusive is None):
        raise DataValidationError(
            f"{line_no}행 {prefix}: end와 end_inclusive는 함께 null이거나 함께 값이 있어야 합니다."
        )
    return VersionRange(start, start_inclusive, end, end_inclusive)


def _normalize_binding(value: Any, line_no: int, index: int) -> Binding:
    prefix = f"bindings[{index}]"
    if not isinstance(value, dict):
        raise DataValidationError(f"{line_no}행 {prefix}: object여야 합니다.")
    required = {"vendor", "product", "version_ranges"}
    missing = required.difference(value)
    if missing:
        raise DataValidationError(f"{line_no}행 {prefix}: 필수 키 누락 {sorted(missing)}")

    vendor = _nullable_string(value["vendor"], f"{prefix}.vendor", line_no)
    product = _nullable_string(value["product"], f"{prefix}.product", line_no)
    if product is None:
        raise DataValidationError(f"{line_no}행 {prefix}.product: null일 수 없습니다.")
    ranges = value["version_ranges"]
    if not isinstance(ranges, list) or not ranges:
        raise DataValidationError(f"{line_no}행 {prefix}.version_ranges: 비어 있지 않은 array여야 합니다.")
    normalized_ranges = tuple(
        _normalize_version_range(item, line_no, f"{prefix}.version_ranges[{range_index}]")
        for range_index, item in enumerate(ranges)
    )
    return Binding(vendor, product, normalized_ranges)


def normalize_record(value: Any, line_no: int) -> TrainingRecord:
    if not isinstance(value, dict):
        raise DataValidationError(f"{line_no}행: JSON object여야 합니다.")
    missing = {"cve_id", "description", "bindings"}.difference(value)
    if missing:
        raise DataValidationError(f"{line_no}행: 필수 키 누락 {sorted(missing)}")

    cve_id = value["cve_id"]
    if not isinstance(cve_id, str) or not CVE_ID_RE.fullmatch(cve_id.strip()):
        raise DataValidationError(f"{line_no}행 cve_id 형식이 올바르지 않습니다: {cve_id!r}")
    description = value["description"]
    if not isinstance(description, str) or not description.strip():
        raise DataValidationError(f"{line_no}행 description이 비어 있습니다.")
    bindings = value["bindings"]
    if not isinstance(bindings, list):
        raise DataValidationError(f"{line_no}행 bindings는 array여야 합니다.")

    return TrainingRecord(
        cve_id=cve_id.strip().upper(),
        description=description.strip(),
        bindings=tuple(
            _normalize_binding(binding, line_no, index)
            for index, binding in enumerate(bindings)
        ),
    )


def load_records(path: Path) -> list[TrainingRecord]:
    if not path.is_file():
        raise DataValidationError(f"학습 JSONL을 찾을 수 없습니다: {path}")

    records: list[TrainingRecord] = []
    seen: dict[str, int] = {}
    with path.open("r", encoding="utf-8") as source:
        for line_no, line in enumerate(source, start=1):
            if not line.strip():
                continue
            try:
                raw = json.loads(line)
            except json.JSONDecodeError as exc:
                raise DataValidationError(f"{line_no}행 JSON 오류: {exc}") from exc
            record = normalize_record(raw, line_no)
            previous = seen.get(record.cve_id)
            if previous is not None:
                raise DataValidationError(
                    f"중복 cve_id {record.cve_id}: {previous}행과 {line_no}행"
                )
            seen[record.cve_id] = line_no
            records.append(record)

    if len(records) < 2:
        raise DataValidationError("train/test 분리를 위해 최소 2개의 고유 레코드가 필요합니다.")
    return records


def _binding_count_bucket(record: TrainingRecord) -> str:
    count = len(record.bindings)
    if count == 0:
        return "0"
    if count == 1:
        return "1"
    if count <= 3:
        return "2-3"
    return "4+"


def _description_length_bucket(record: TrainingRecord) -> str:
    length = len(record.description)
    if length <= 512:
        return "<=512"
    if length <= 1024:
        return "513-1024"
    if length <= 2048:
        return "1025-2048"
    return "2049+"


def _version_shape_bucket(record: TrainingRecord) -> str:
    if not record.bindings:
        return "empty-bindings"
    shapes: set[str] = set()
    for binding in record.bindings:
        for version_range in binding.version_ranges:
            start, end = version_range.start, version_range.end
            if start is None and end is None:
                shapes.add("no-version")
            elif (
                start is not None
                and start == end
                and version_range.start_inclusive is True
                and version_range.end_inclusive is True
            ):
                shapes.add("exact")
            elif start is None:
                shapes.add("upper")
            elif end is None:
                shapes.add("lower")
            else:
                shapes.add("bounded")
    return next(iter(shapes)) if len(shapes) == 1 else "mixed"


def record_stratum(record: TrainingRecord) -> tuple[str, str, str]:
    """Use model-relevant, tokenizer-independent buckets for split balance."""
    return (
        _binding_count_bucket(record),
        _description_length_bucket(record),
        _version_shape_bucket(record),
    )


def _normalized_group_product(product: str) -> str:
    compact = re.sub(r"[^A-Za-z0-9]+", "", product)
    if len(compact) <= 4:
        # Keep the case signature for short names so Cisco IOS and Apple iOS
        # do not collapse into the same group.
        return compact
    return compact.casefold()


def _description_group_fingerprint(description: str) -> str:
    normalized = " ".join(description.casefold().split())
    return hashlib.sha256(normalized.encode("utf-8")).hexdigest()


def record_group_keys(record: TrainingRecord) -> tuple[str, ...]:
    """Return leakage-prevention keys; shared keys form connected components."""
    keys = {
        f"product:{_normalized_group_product(binding.product)}"
        for binding in record.bindings
        if _normalized_group_product(binding.product)
    }
    # Exact duplicate descriptions must remain together even if labels differ.
    keys.add(f"description:{_description_group_fingerprint(record.description)}")
    return tuple(sorted(keys))


def make_record_groups(
    records: Sequence[TrainingRecord],
) -> tuple[list[list[TrainingRecord]], dict[str, str]]:
    """Build transitive product/duplicate-description connected components."""
    parents = list(range(len(records)))
    sizes = [1] * len(records)

    def find(index: int) -> int:
        while parents[index] != index:
            parents[index] = parents[parents[index]]
            index = parents[index]
        return index

    def union(left: int, right: int) -> None:
        left_root, right_root = find(left), find(right)
        if left_root == right_root:
            return
        if sizes[left_root] < sizes[right_root]:
            left_root, right_root = right_root, left_root
        parents[right_root] = left_root
        sizes[left_root] += sizes[right_root]

    owner_by_key: dict[str, int] = {}
    for index, record in enumerate(records):
        for key in record_group_keys(record):
            previous = owner_by_key.get(key)
            if previous is None:
                owner_by_key[key] = index
            else:
                union(index, previous)

    records_by_root: dict[int, list[TrainingRecord]] = {}
    keys_by_root: dict[int, set[str]] = {}
    for index, record in enumerate(records):
        root = find(index)
        records_by_root.setdefault(root, []).append(record)
        keys_by_root.setdefault(root, set()).update(record_group_keys(record))

    ordered_roots = sorted(
        records_by_root,
        key=lambda root: min(record.cve_id for record in records_by_root[root]),
    )
    groups: list[list[TrainingRecord]] = []
    group_by_cve: dict[str, str] = {}
    for root in ordered_roots:
        group = sorted(records_by_root[root], key=lambda record: record.cve_id)
        identity = "\n".join(
            [*(sorted(keys_by_root[root])), *(record.cve_id for record in group)]
        )
        group_id = "group-" + hashlib.sha256(identity.encode("utf-8")).hexdigest()[:16]
        groups.append(group)
        for record in group:
            group_by_cve[record.cve_id] = group_id
    return groups, group_by_cve


def _stratum_key(stratum: tuple[str, str, str]) -> str:
    return "|".join(stratum)


def make_stratified_group_partitions(
    records: Sequence[TrainingRecord], num_partitions: int, seed: int
) -> tuple[list[list[TrainingRecord]], dict[str, Any]]:
    """Greedily balance strata while never splitting a product component."""
    if num_partitions < 2:
        raise ValueError("num_partitions는 2 이상이어야 합니다.")
    if len(records) < num_partitions:
        raise DataValidationError(
            f"레코드 {len(records)}건보다 분할 단위 {num_partitions}가 큽니다."
        )

    groups, group_by_cve = make_record_groups(records)
    if len(groups) < num_partitions:
        raise DataValidationError(
            f"독립 product group {len(groups)}개보다 분할 단위 {num_partitions}가 큽니다."
        )

    total_strata: dict[tuple[str, str, str], int] = {}
    group_strata: list[dict[tuple[str, str, str], int]] = []
    for group in groups:
        counts: dict[tuple[str, str, str], int] = {}
        for record in group:
            stratum = record_stratum(record)
            counts[stratum] = counts.get(stratum, 0) + 1
            total_strata[stratum] = total_strata.get(stratum, 0) + 1
        group_strata.append(counts)

    rng = random.Random(seed)
    tie_breakers = list(range(len(groups)))
    rng.shuffle(tie_breakers)
    tie_priority = {group_index: order for order, group_index in enumerate(tie_breakers)}
    ordered_group_indices = sorted(
        range(len(groups)),
        key=lambda index: (
            -len(groups[index]),
            -max(group_strata[index].values()),
            tie_priority[index],
        ),
    )

    partitions: list[list[TrainingRecord]] = [[] for _ in range(num_partitions)]
    partition_groups: list[list[int]] = [[] for _ in range(num_partitions)]
    partition_totals = [0] * num_partitions
    partition_strata: list[dict[tuple[str, str, str], int]] = [
        {} for _ in range(num_partitions)
    ]
    fold_priority = list(range(num_partitions))
    rng.shuffle(fold_priority)
    fold_tie = {fold: order for order, fold in enumerate(fold_priority)}
    target_size = len(records) / num_partitions

    def assignment_delta(group_index: int, fold: int) -> tuple[float, int, int]:
        size = len(groups[group_index])
        before_size = partition_totals[fold]
        size_delta = (
            ((before_size + size - target_size) / max(target_size, 1.0)) ** 2
            - ((before_size - target_size) / max(target_size, 1.0)) ** 2
        )
        stratum_delta = 0.0
        for stratum, addition in group_strata[group_index].items():
            target = total_strata[stratum] / num_partitions
            before = partition_strata[fold].get(stratum, 0)
            denominator = max(target, 1.0)
            stratum_delta += (
                ((before + addition - target) / denominator) ** 2
                - ((before - target) / denominator) ** 2
            )
        return stratum_delta + size_delta, partition_totals[fold], fold_tie[fold]

    for group_index in ordered_group_indices:
        selected = min(
            range(num_partitions),
            key=lambda fold: assignment_delta(group_index, fold),
        )
        partitions[selected].extend(groups[group_index])
        partition_groups[selected].append(group_index)
        partition_totals[selected] += len(groups[group_index])
        for stratum, addition in group_strata[group_index].items():
            partition_strata[selected][stratum] = (
                partition_strata[selected].get(stratum, 0) + addition
            )

    for fold, partition in enumerate(partitions):
        random.Random(seed + 20_000 + fold).shuffle(partition)
    if any(not partition for partition in partitions):
        raise DataValidationError("비어 있는 stratified group partition이 생성되었습니다.")

    assigned_ids = [record.cve_id for partition in partitions for record in partition]
    expected_ids = [record.cve_id for record in records]
    if len(assigned_ids) != len(set(assigned_ids)) or set(assigned_ids) != set(expected_ids):
        raise RuntimeError("stratified group 배정 중 레코드 누락 또는 중복이 발생했습니다.")
    for group in groups:
        fold_ids = {
            fold
            for fold, partition in enumerate(partitions)
            if any(record.cve_id in {item.cve_id for item in partition} for record in group)
        }
        if len(fold_ids) != 1:
            raise RuntimeError("동일 product group이 여러 partition으로 분리되었습니다.")

    metadata = {
        "scheme": "stratified_product_group_partitions",
        "seed": seed,
        "num_partitions": num_partitions,
        "stratify_by": [
            "binding_count",
            "description_length",
            "version_range_shape",
        ],
        "group_by": [
            "normalized_product_connected_components",
            "exact_description_fingerprint",
        ],
        "group_count": len(groups),
        "largest_group_size": max(len(group) for group in groups),
        "partition_counts": [len(partition) for partition in partitions],
        "partition_group_counts": [len(items) for items in partition_groups],
        "partition_empty_binding_counts": [
            sum(not record.bindings for record in partition)
            for partition in partitions
        ],
        "partition_stratum_counts": [
            {
                _stratum_key(stratum): count
                for stratum, count in sorted(counts.items())
            }
            for counts in partition_strata
        ],
        "group_by_cve": group_by_cve,
    }
    return partitions, metadata


def make_stratified_partitions(
    records: Sequence[TrainingRecord], num_partitions: int, seed: int
) -> list[list[TrainingRecord]]:
    """Create deterministic partitions balanced by binding count and text length."""
    if num_partitions < 2:
        raise ValueError("num_partitions는 2 이상이어야 합니다.")
    if len(records) < num_partitions:
        raise DataValidationError(
            f"레코드 {len(records)}건보다 분할 단위 {num_partitions}가 큽니다."
        )

    strata: dict[tuple[str, str], list[TrainingRecord]] = {}
    for record in sorted(records, key=lambda item: item.cve_id):
        strata.setdefault(record_stratum(record), []).append(record)

    rng = random.Random(seed)
    partitions: list[list[TrainingRecord]] = [[] for _ in range(num_partitions)]
    totals = [0] * num_partitions
    # Large strata go first. Each stratum is kept within one record per
    # partition, while total size resolves ties between equal candidates.
    ordered_strata = sorted(strata.items(), key=lambda item: (-len(item[1]), item[0]))
    for _, group in ordered_strata:
        group = list(group)
        rng.shuffle(group)
        stratum_counts = [0] * num_partitions
        tie_priority = list(range(num_partitions))
        rng.shuffle(tie_priority)
        priority = {partition: order for order, partition in enumerate(tie_priority)}
        for record in group:
            selected = min(
                range(num_partitions),
                key=lambda partition: (
                    stratum_counts[partition],
                    totals[partition],
                    priority[partition],
                ),
            )
            partitions[selected].append(record)
            stratum_counts[selected] += 1
            totals[selected] += 1

    for partition in partitions:
        rng.shuffle(partition)
    if any(not partition for partition in partitions):
        raise DataValidationError("비어 있는 train/test 분할 단위가 생성되었습니다.")

    assigned_ids = [record.cve_id for partition in partitions for record in partition]
    expected_ids = [record.cve_id for record in records]
    if len(assigned_ids) != len(set(assigned_ids)) or set(assigned_ids) != set(expected_ids):
        raise RuntimeError("train/test 배정 중 레코드 누락 또는 중복이 발생했습니다.")
    return partitions


def split_train_test(
    records: Sequence[TrainingRecord],
    split_ratio: tuple[int, int],
    seed: int,
) -> tuple[list[TrainingRecord], list[TrainingRecord], dict[str, Any]]:
    """Create one fixed stratified train/test split."""
    train_units, test_units = split_ratio
    total_units = sum(split_ratio)
    partitions = make_stratified_partitions(records, total_units, seed)
    train = [
        record for partition in partitions[:train_units] for record in partition
    ]
    test = [record for partition in partitions[train_units:] for record in partition]
    random.Random(seed + 10_001).shuffle(train)
    random.Random(seed + 10_002).shuffle(test)

    train_ids = {record.cve_id for record in train}
    test_ids = {record.cve_id for record in test}
    if not train or not test:
        raise DataValidationError("train/test 중 비어 있는 split이 있습니다.")
    if train_ids.intersection(test_ids):
        raise RuntimeError("train/test 사이에 CVE ID 누수가 있습니다.")
    if train_ids.union(test_ids) != {record.cve_id for record in records}:
        raise RuntimeError("train/test 분할 중 레코드 누락이 발생했습니다.")

    metadata = {
        "scheme": "stratified_train_test",
        "ratio": {"train": train_units, "test": test_units},
        "seed": seed,
        "stratify_by": ["binding_count", "description_length"],
        "counts": {"train": len(train), "test": len(test)},
        "empty_binding_counts": {
            "train": sum(not record.bindings for record in train),
            "test": sum(not record.bindings for record in test),
        },
    }
    return train, test, metadata


def split_development_test_grouped(
    records: Sequence[TrainingRecord],
    split_ratio: tuple[int, int],
    seed: int,
) -> tuple[list[TrainingRecord], list[TrainingRecord], dict[str, Any]]:
    """Create a locked test split without product-group leakage."""
    development_units, test_units = split_ratio
    partitions, partition_metadata = make_stratified_group_partitions(
        records, sum(split_ratio), seed
    )
    development = [
        record
        for partition in partitions[:development_units]
        for record in partition
    ]
    locked_test = [
        record
        for partition in partitions[development_units:]
        for record in partition
    ]
    random.Random(seed + 10_001).shuffle(development)
    random.Random(seed + 10_002).shuffle(locked_test)

    development_ids = {record.cve_id for record in development}
    test_ids = {record.cve_id for record in locked_test}
    if not development or not locked_test:
        raise DataValidationError("development/test 중 비어 있는 split이 있습니다.")
    if development_ids.intersection(test_ids):
        raise RuntimeError("development/test 사이에 CVE ID 누수가 있습니다.")
    group_by_cve = partition_metadata["group_by_cve"]
    development_groups = {group_by_cve[cve_id] for cve_id in development_ids}
    test_groups = {group_by_cve[cve_id] for cve_id in test_ids}
    if development_groups.intersection(test_groups):
        raise RuntimeError("development/test 사이에 product group 누수가 있습니다.")

    metadata = {
        "scheme": "stratified_product_group_development_test",
        "ratio": {"development": development_units, "test": test_units},
        "seed": seed,
        "counts": {
            "development": len(development),
            "locked_test": len(locked_test),
        },
        "empty_binding_counts": {
            "development": sum(not record.bindings for record in development),
            "locked_test": sum(not record.bindings for record in locked_test),
        },
        "partitioning": partition_metadata,
    }
    return development, locked_test, metadata


def make_cv_folds(
    development_records: Sequence[TrainingRecord],
    cv_folds: int,
    seed: int,
) -> tuple[list[CVFold], dict[str, Any]]:
    """Create K validation folds; every development record is OOF exactly once."""
    partitions, partition_metadata = make_stratified_group_partitions(
        development_records, cv_folds, seed + 30_000
    )
    expected_ids = {record.cve_id for record in development_records}
    folds: list[CVFold] = []
    validation_occurrences: Counter[str] = Counter()
    for fold_index in range(cv_folds):
        validation = list(partitions[fold_index])
        train = [
            record
            for index, partition in enumerate(partitions)
            if index != fold_index
            for record in partition
        ]
        random.Random(seed + 40_000 + fold_index).shuffle(train)
        random.Random(seed + 50_000 + fold_index).shuffle(validation)
        train_ids = {record.cve_id for record in train}
        validation_ids = {record.cve_id for record in validation}
        if train_ids.intersection(validation_ids):
            raise RuntimeError(f"CV fold {fold_index + 1}: train/validation ID 누수")
        if train_ids.union(validation_ids) != expected_ids:
            raise RuntimeError(f"CV fold {fold_index + 1}: 레코드 누락")
        group_by_cve = partition_metadata["group_by_cve"]
        train_groups = {group_by_cve[cve_id] for cve_id in train_ids}
        validation_groups = {group_by_cve[cve_id] for cve_id in validation_ids}
        if train_groups.intersection(validation_groups):
            raise RuntimeError(
                f"CV fold {fold_index + 1}: train/validation product group 누수"
            )
        validation_occurrences.update(validation_ids)
        folds.append(
            CVFold(
                index=fold_index + 1,
                train_records=tuple(train),
                validation_records=tuple(validation),
                metadata={
                    "fold_index": fold_index + 1,
                    "train_count": len(train),
                    "validation_count": len(validation),
                    "train_group_count": len(train_groups),
                    "validation_group_count": len(validation_groups),
                    "empty_binding_counts": {
                        "train": sum(not record.bindings for record in train),
                        "validation": sum(not record.bindings for record in validation),
                    },
                    "train_cve_ids": [record.cve_id for record in train],
                    "validation_cve_ids": [
                        record.cve_id for record in validation
                    ],
                },
            )
        )
    if set(validation_occurrences) != expected_ids or any(
        count != 1 for count in validation_occurrences.values()
    ):
        raise RuntimeError("각 development 레코드가 validation에 정확히 한 번 배정되지 않았습니다.")
    metadata = {
        "scheme": "stratified_product_group_kfold",
        "cv_folds": cv_folds,
        "seed": seed,
        "development_count": len(development_records),
        "fold_counts": [
            {
                "fold_index": fold.index,
                "train": len(fold.train_records),
                "validation": len(fold.validation_records),
            }
            for fold in folds
        ],
        "partitioning": partition_metadata,
    }
    return folds, metadata


def user_prompt(record: TrainingRecord) -> str:
    return f"CVE ID: {record.cve_id}\nDescription:\n{record.description}"


def target_json(record: TrainingRecord) -> str:
    payload = {
        "bindings": [
            {
                "vendor": binding.vendor,
                "product": binding.product,
                "version_ranges": [asdict(version_range) for version_range in binding.version_ranges],
            }
            for binding in record.bindings
        ]
    }
    return json.dumps(payload, ensure_ascii=False, separators=(",", ":"))


def chat_template_ids(
    tokenizer: Any,
    messages: list[dict[str, str]],
    *,
    add_generation_prompt: bool,
) -> list[int]:
    """Return token IDs consistently across Transformers 4.x and 5.x.

    Transformers 5 changed ``apply_chat_template`` to return a BatchEncoding by
    default.  Requesting a dictionary and selecting ``input_ids`` explicitly
    avoids depending on that version-specific default.
    """
    result = tokenizer.apply_chat_template(
        messages,
        tokenize=True,
        add_generation_prompt=add_generation_prompt,
        return_dict=True,
    )
    try:
        input_ids = result["input_ids"]
    except (KeyError, TypeError) as exc:
        raise RuntimeError("chat template 결과에 input_ids가 없습니다.") from exc
    if not isinstance(input_ids, list) or (
        input_ids and (isinstance(input_ids[0], bool) or not isinstance(input_ids[0], int))
    ):
        raise RuntimeError(
            "chat template의 input_ids가 단일 token ID 목록이 아닙니다. "
            "단일 conversation 입력인지 확인하세요."
        )
    return input_ids


def encode_records(
    records: Sequence[TrainingRecord], tokenizer: Any, max_seq_length: int
) -> tuple[list[dict[str, list[int]]], list[int]]:
    encoded: list[dict[str, list[int]]] = []
    lengths: list[int] = []
    overlength: list[tuple[str, int]] = []

    for record in records:
        prompt_messages = [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": user_prompt(record)},
        ]
        full_messages = [
            *prompt_messages,
            {"role": "assistant", "content": target_json(record)},
        ]
        prompt_ids = chat_template_ids(
            tokenizer, prompt_messages, add_generation_prompt=True
        )
        full_ids = chat_template_ids(
            tokenizer, full_messages, add_generation_prompt=False
        )
        if full_ids[: len(prompt_ids)] != prompt_ids:
            raise RuntimeError(
                "토크나이저 chat template에서 assistant 응답 경계를 찾지 못했습니다. "
                "Qwen3 Instruct tokenizer인지 확인하세요."
            )
        assistant_token_count = len(full_ids) - len(prompt_ids)
        if assistant_token_count <= 0:
            raise RuntimeError(f"assistant 학습 token이 없습니다: {record.cve_id}")

        length = len(full_ids)
        lengths.append(length)
        if length > max_seq_length:
            overlength.append((record.cve_id, length))
            continue
        encoded.append(
            {
                "input_ids": full_ids,
                "attention_mask": [1] * length,
                "labels": [-100] * len(prompt_ids) + full_ids[len(prompt_ids) :],
            }
        )

    if overlength:
        examples = ", ".join(
            f"{cve_id}={length}" for cve_id, length in sorted(overlength, key=lambda x: -x[1])[:10]
        )
        required = max(length for _, length in overlength)
        raise DataValidationError(
            f"{len(overlength)}건이 --max-seq-length {max_seq_length}를 초과합니다 "
            f"({examples}). 정답 JSON을 자르지 않도록 최소 {required} 이상으로 올리세요."
        )
    return encoded, lengths


def percentile(values: Sequence[int], probability: float) -> int:
    ordered = sorted(values)
    index = min(len(ordered) - 1, math.ceil(probability * len(ordered)) - 1)
    return ordered[index]


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for block in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


