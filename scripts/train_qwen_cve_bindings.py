#!/usr/bin/env python3
"""QLoRA supervised fine-tuning for CVE vendor/product/version extraction.

The input is one JSONL file containing the merged gold and silver records.  Each
line must provide ``cve_id``, ``description``, and ``bindings`` in the same shape
as ``data/cve_bindings_merged-800-hardrule-v1.jsonl``.  Any top-level provenance
metadata is ignored.  In cross-validation mode, records are first split into
90% development and 10% locked test data using product-group-aware
stratification.  Only the development records participate in K-fold CV; the
locked test records are never evaluated by the CV run.

The model learns to emit only ``{"bindings": [...]}``; ``cve_id`` and the source
description should be copied from the NVD input by the later inference pipeline,
not regenerated by the model.

Single RTX 2080 Ti example::

    python scripts/train_qwen_cve_bindings.py \
      --data data/cve_bindings_merged-800-hardrule-v1.jsonl \
      --model Qwen/Qwen3-4B-Instruct-2507 \
      --output-dir models/qwen3-4b-cve-bindings-9to1

Seven-GPU DDP example (lower accumulation keeps the global batch reasonable)::

    torchrun --standalone --nproc-per-node=7 \
      scripts/train_qwen_cve_bindings.py \
      --data data/cve_bindings_merged-800-hardrule-v1.jsonl \
      --cv-folds 5 \
      --gradient-accumulation-steps 1

"""

