def make_chunked_causal_lm_loss(torch: Any, chunk_size: int):
    """Compute causal LM loss without a full float32 vocabulary-logit copy.

    Transformers' default causal loss casts every logit to float32 at once.
    Qwen3 has a vocabulary of roughly 152k tokens, so one 3,800-token example
    needs another ~2.2 GiB just for that cast.  Checkpointing each token chunk
    keeps the numerically stable float32 cross-entropy while bounding its peak
    memory; the chunk is recomputed during backward instead of being retained.
    """

    def chunked_loss(
        logits: Any,
        labels: Any,
        vocab_size: int,
        num_items_in_batch: Any = None,
        ignore_index: int = -100,
        **_: Any,
    ) -> Any:
        if logits.shape[-1] != vocab_size:
            raise RuntimeError(
                f"logit vocabulary 크기 불일치: {logits.shape[-1]} != {vocab_size}"
            )

        # logits_to_keep retains the suffix beginning one token before the
        # assistant answer.  Select the matching next-token labels.
        shifted = torch.nn.functional.pad(labels, (0, 1), value=ignore_index)
        shifted = shifted[..., -logits.shape[-2] :].contiguous()
        flat_logits = logits.reshape(-1, vocab_size)
        flat_labels = shifted.reshape(-1).to(logits.device)

        def cross_entropy_sum(logit_chunk: Any, label_chunk: Any) -> Any:
            return torch.nn.functional.cross_entropy(
                logit_chunk.float(),
                label_chunk,
                ignore_index=ignore_index,
                reduction="sum",
            )

        parts: list[Any] = []
        for start in range(0, flat_logits.shape[0], chunk_size):
            logit_chunk = flat_logits[start : start + chunk_size]
            label_chunk = flat_labels[start : start + chunk_size]
            if torch.is_grad_enabled() and logit_chunk.requires_grad:
                part = torch.utils.checkpoint.checkpoint(
                    cross_entropy_sum,
                    logit_chunk,
                    label_chunk,
                    use_reentrant=True,
                )
            else:
                part = cross_entropy_sum(logit_chunk, label_chunk)
            parts.append(part)

        if not parts:
            raise RuntimeError("loss를 계산할 token이 없습니다.")
        total = torch.stack(parts).sum()
        if num_items_in_batch is not None:
            denominator = num_items_in_batch.to(total.device) if torch.is_tensor(
                num_items_in_batch
            ) else num_items_in_batch
        else:
            denominator = (flat_labels != ignore_index).sum().clamp_min(1)
        return total / denominator

    return chunked_loss


def evaluate_test_metrics(
    *,
    torch: Any,
    model: Any,
    encoded_test: Sequence[dict[str, list[int]]],
    data_collator: Any,
    device: Any,
    rank: int,
    world_size: int,
    batch_size: int,
) -> dict[str, float | int]:
    """Evaluate unique test shards before any cross-rank sequence padding.

    Transformers pads variable-length logits on the right *before* calling
    ``preprocess_logits_for_metrics``.  Our logits contain only the assistant
    suffix, so aligning those padded suffixes against independently padded full
    labels shifts token positions across DDP ranks.  Instead, each rank reduces
    its unpadded local logits to scalar counts and only those counts are summed.
    """
    local_examples = list(encoded_test[rank::world_size])

    distributed = (
        torch.distributed.is_available() and torch.distributed.is_initialized()
    )
    if distributed:
        torch.distributed.barrier(device_ids=[device.index])
    torch.cuda.synchronize(device)
    started_at = time.perf_counter()

    # loss sum, correct tokens, supervised tokens, exact records, records
    totals = torch.zeros(5, dtype=torch.float64, device=device)
    model.eval()
    with torch.inference_mode():
        for start in range(0, len(local_examples), batch_size):
            features = local_examples[start : start + batch_size]
            batch = data_collator(features)
            batch = {
                key: value.to(device) if torch.is_tensor(value) else value
                for key, value in batch.items()
            }
            labels = batch["labels"]
            outputs = model(**batch)
            logits = outputs.logits

            ignore_index = -100
            shifted = torch.nn.functional.pad(labels, (0, 1), value=ignore_index)
            shifted = shifted[..., -logits.shape[-2] :].to(logits.device)
            supervised = shifted.ne(ignore_index)
            correct = logits.argmax(dim=-1).eq(shifted) & supervised
            correct_per_record = correct.sum(dim=-1)
            tokens_per_record = supervised.sum(dim=-1)
            if not tokens_per_record.gt(0).all():
                raise RuntimeError("test batch에 정답 assistant token이 없는 record가 있습니다.")

            token_count = tokens_per_record.sum()
            totals[0] += outputs.loss.detach().to(torch.float64) * token_count
            totals[1] += correct_per_record.sum()
            totals[2] += token_count
            totals[3] += correct_per_record.eq(tokens_per_record).sum()
            totals[4] += labels.shape[0]

    torch.cuda.synchronize(device)
    elapsed = torch.tensor(
        time.perf_counter() - started_at, dtype=torch.float64, device=device
    )
    if distributed:
        torch.distributed.all_reduce(totals, op=torch.distributed.ReduceOp.SUM)
        torch.distributed.all_reduce(elapsed, op=torch.distributed.ReduceOp.MAX)

    loss_sum, correct_tokens, supervised_tokens, exact_records, record_count = (
        totals.tolist()
    )
    if supervised_tokens <= 0 or record_count <= 0:
        raise RuntimeError("test metric을 계산할 정답 token 또는 record가 없습니다.")
    expected_records = len(encoded_test)
    if int(record_count) != expected_records:
        raise RuntimeError(
            f"test 집계 record 수 불일치: {int(record_count)} != {expected_records}"
        )

    runtime = elapsed.item()
    max_steps_per_rank = math.ceil(
        math.ceil(expected_records / world_size) / batch_size
    )
    return {
        "test_loss": loss_sum / supervised_tokens,
        "test_accuracy": correct_tokens / supervised_tokens,
        "test_teacher_forced_exact_match": exact_records / record_count,
        "test_correct_tokens": int(correct_tokens),
        "test_supervised_tokens": int(supervised_tokens),
        "test_exact_match_count": int(exact_records),
        "test_samples": int(record_count),
        "test_runtime": runtime,
        "test_samples_per_second": record_count / runtime,
        "test_steps_per_second": max_steps_per_rank / runtime,
    }


def validate_generated_bindings_payload(payload: Any) -> dict[str, Any]:
    if not isinstance(payload, dict) or set(payload) != {"bindings"}:
        raise ValueError('최상위 JSON은 단일 키 "bindings"만 가져야 합니다.')
    if not isinstance(payload["bindings"], list):
        raise ValueError("bindings가 array가 아닙니다.")
    normalized_bindings: list[dict[str, Any]] = []
    for binding_index, binding in enumerate(payload["bindings"]):
        prefix = f"bindings[{binding_index}]"
        if not isinstance(binding, dict) or set(binding) != {
            "vendor",
            "product",
            "version_ranges",
        }:
            raise ValueError(f"{prefix}: 필드 구성이 올바르지 않습니다.")
        vendor, product = binding["vendor"], binding["product"]
        if vendor is not None and not isinstance(vendor, str):
            raise ValueError(f"{prefix}.vendor: string 또는 null이어야 합니다.")
        if not isinstance(product, str) or not product:
            raise ValueError(f"{prefix}.product가 비어 있거나 string이 아닙니다.")
        raw_ranges = binding["version_ranges"]
        if not isinstance(raw_ranges, list) or not raw_ranges:
            raise ValueError(f"{prefix}.version_ranges가 비어 있습니다.")
        normalized_ranges: list[dict[str, Any]] = []
        for range_index, version_range in enumerate(raw_ranges):
            range_prefix = f"{prefix}.version_ranges[{range_index}]"
            if not isinstance(version_range, dict) or set(version_range) != {
                "start",
                "start_inclusive",
                "end",
                "end_inclusive",
            }:
                raise ValueError(f"{range_prefix}: 필드 구성이 올바르지 않습니다.")
            for endpoint in ("start", "end"):
                inclusive = f"{endpoint}_inclusive"
                value = version_range[endpoint]
                flag = version_range[inclusive]
                if value is not None and not isinstance(value, str):
                    raise ValueError(f"{range_prefix}.{endpoint}: string/null 필요")
                if flag is not None and not isinstance(flag, bool):
                    raise ValueError(f"{range_prefix}.{inclusive}: boolean/null 필요")
                if (value is None) != (flag is None):
                    raise ValueError(
                        f"{range_prefix}: {endpoint}와 {inclusive}는 함께 null이어야 합니다."
                    )
            normalized_ranges.append(
                {
                    "start": version_range["start"],
                    "start_inclusive": version_range["start_inclusive"],
                    "end": version_range["end"],
                    "end_inclusive": version_range["end_inclusive"],
                }
            )
        normalized_bindings.append(
            {
                "vendor": vendor,
                "product": product,
                "version_ranges": normalized_ranges,
            }
        )
    return {"bindings": normalized_bindings}


def canonical_generated_payload(
    payload: dict[str, Any], *, normalize_strings: bool
) -> tuple[Any, ...]:
    def normalize(value: Any) -> Any:
        if not normalize_strings or not isinstance(value, str):
            return value
        return re.sub(r"[^a-z0-9]+", "", value.casefold())

    bindings: list[tuple[Any, ...]] = []
    for binding in payload["bindings"]:
        ranges = [
            (
                normalize(version_range["start"]),
                version_range["start_inclusive"],
                normalize(version_range["end"]),
                version_range["end_inclusive"],
            )
            for version_range in binding["version_ranges"]
        ]
        bindings.append(
            (
                normalize(binding["vendor"]),
                normalize(binding["product"]),
                tuple(sorted(ranges, key=repr)),
            )
        )
    return tuple(sorted(bindings, key=repr))


def record_target_payload(record: TrainingRecord) -> dict[str, Any]:
    return json.loads(target_json(record))


def _eos_token_ids(tokenizer: Any, model: Any) -> set[int]:
    values = [
        tokenizer.eos_token_id,
        getattr(model.generation_config, "eos_token_id", None),
    ]
    result: set[int] = set()
    for value in values:
        if isinstance(value, int):
            result.add(value)
        elif isinstance(value, (list, tuple)):
            result.update(item for item in value if isinstance(item, int))
    return result


def evaluate_generation_metrics(
    *,
    torch: Any,
    model: Any,
    tokenizer: Any,
    records: Sequence[TrainingRecord],
    system_prompt: str,
    device: Any,
    rank: int,
    world_size: int,
    batch_size: int,
    max_new_tokens: int,
) -> tuple[dict[str, float | int], list[dict[str, Any]]]:
    """Run greedy free generation and gather OOF-ready per-record predictions."""
    local_items = list(enumerate(records))[rank::world_size]
    distributed = (
        torch.distributed.is_available() and torch.distributed.is_initialized()
    )
    if distributed:
        torch.distributed.barrier(device_ids=[device.index])
    torch.cuda.synchronize(device)
    started_at = time.perf_counter()
    eos_ids = _eos_token_ids(tokenizer, model)
    local_predictions: list[dict[str, Any]] = []
    # valid, strict, order-insensitive, normalized, records, generation-limit
    totals = torch.zeros(6, dtype=torch.float64, device=device)
    model.eval()
    original_use_cache = model.config.use_cache
    model.config.use_cache = True
    try:
        for batch_start in range(0, len(local_items), batch_size):
            batch_items = local_items[batch_start : batch_start + batch_size]
            prompt_ids = [
                chat_template_ids(
                    tokenizer,
                    [
                        {"role": "system", "content": system_prompt},
                        {"role": "user", "content": user_prompt(record)},
                    ],
                    add_generation_prompt=True,
                )
                for _, record in batch_items
            ]
            max_prompt_length = max(len(ids) for ids in prompt_ids)
            padded_ids = [
                [tokenizer.pad_token_id] * (max_prompt_length - len(ids)) + ids
                for ids in prompt_ids
            ]
            attention_masks = [
                [0] * (max_prompt_length - len(ids)) + [1] * len(ids)
                for ids in prompt_ids
            ]
            with torch.inference_mode():
                sequences = model.generate(
                    input_ids=torch.tensor(
                        padded_ids, dtype=torch.long, device=device
                    ),
                    attention_mask=torch.tensor(
                        attention_masks, dtype=torch.long, device=device
                    ),
                    do_sample=False,
                    max_new_tokens=max_new_tokens,
                    pad_token_id=tokenizer.pad_token_id,
                    eos_token_id=tokenizer.eos_token_id,
                    use_cache=True,
                )
            for row, (evaluation_index, record) in enumerate(batch_items):
                generated_ids = sequences[row, max_prompt_length:].tolist()
                eos_position = next(
                    (
                        index
                        for index, token_id in enumerate(generated_ids)
                        if token_id in eos_ids
                    ),
                    None,
                )
                hit_limit = (
                    eos_position is None and len(generated_ids) >= max_new_tokens
                )
                content_ids = (
                    generated_ids
                    if eos_position is None
                    else generated_ids[:eos_position]
                )
                raw_output = tokenizer.decode(
                    content_ids, skip_special_tokens=True
                ).strip()
                gold = record_target_payload(record)
                prediction: dict[str, Any] | None = None
                error: str | None = None
                try:
                    prediction = validate_generated_bindings_payload(
                        json.loads(raw_output)
                    )
                except (json.JSONDecodeError, ValueError) as exc:
                    error = f"{type(exc).__name__}: {exc}"
                strict = prediction == gold if prediction is not None else False
                order_insensitive = (
                    canonical_generated_payload(
                        prediction, normalize_strings=False
                    )
                    == canonical_generated_payload(gold, normalize_strings=False)
                    if prediction is not None
                    else False
                )
                normalized = (
                    canonical_generated_payload(
                        prediction, normalize_strings=True
                    )
                    == canonical_generated_payload(gold, normalize_strings=True)
                    if prediction is not None
                    else False
                )
                totals[0] += prediction is not None
                totals[1] += strict
                totals[2] += order_insensitive
                totals[3] += normalized
                totals[4] += 1
                totals[5] += hit_limit
                local_predictions.append(
                    {
                        "evaluation_index": evaluation_index,
                        "cve_id": record.cve_id,
                        "description": record.description,
                        "gold": gold,
                        "prediction": prediction,
                        "raw_model_output": raw_output,
                        "status": (
                            "invalid_model_output"
                            if prediction is None
                            else "generation_limit"
                            if hit_limit
                            else "ok"
                        ),
                        "error": error,
                        "generated_tokens": len(content_ids),
                        "strict_exact": strict,
                        "order_insensitive_exact": order_insensitive,
                        "normalized_exact": normalized,
                    }
                )
    finally:
        model.config.use_cache = original_use_cache

    torch.cuda.synchronize(device)
    elapsed = torch.tensor(
        time.perf_counter() - started_at, dtype=torch.float64, device=device
    )
    if distributed:
        torch.distributed.all_reduce(totals, op=torch.distributed.ReduceOp.SUM)
        torch.distributed.all_reduce(elapsed, op=torch.distributed.ReduceOp.MAX)
        gathered: list[Any] = [None] * world_size
        torch.distributed.all_gather_object(gathered, local_predictions)
        all_predictions = [
            prediction for rank_items in gathered for prediction in rank_items
        ]
    else:
        all_predictions = local_predictions

    valid, strict, order_insensitive, normalized, sample_count, limits = (
        totals.tolist()
    )
    if int(sample_count) != len(records):
        raise RuntimeError(
            f"generation 평가 record 수 불일치: {int(sample_count)} != {len(records)}"
        )
    runtime = elapsed.item()
    all_predictions.sort(key=lambda item: item["evaluation_index"])
    metrics: dict[str, float | int] = {
        "generation_valid_rate": valid / sample_count,
        "generation_strict_exact_match": strict / sample_count,
        "generation_order_insensitive_exact_match": (
            order_insensitive / sample_count
        ),
        "generation_normalized_exact_match": normalized / sample_count,
        "generation_valid_count": int(valid),
        "generation_strict_exact_count": int(strict),
        "generation_order_insensitive_exact_count": int(order_insensitive),
        "generation_normalized_exact_count": int(normalized),
        "generation_limit_count": int(limits),
        "generation_samples": int(sample_count),
        "generation_runtime": runtime,
        "generation_samples_per_second": sample_count / runtime,
    }
    return metrics, all_predictions if rank == 0 else []


def make_collator(torch: Any, pad_token_id: int):
    def collate(features: list[dict[str, list[int]]]) -> dict[str, Any]:
        max_length = max(len(feature["input_ids"]) for feature in features)
        max_length = math.ceil(max_length / 8) * 8
        input_ids: list[list[int]] = []
        attention_masks: list[list[int]] = []
        labels: list[list[int]] = []
        for feature in features:
            padding = max_length - len(feature["input_ids"])
            input_ids.append(feature["input_ids"] + [pad_token_id] * padding)
            attention_masks.append(feature["attention_mask"] + [0] * padding)
            labels.append(feature["labels"] + [-100] * padding)
        batch = {
            "input_ids": torch.tensor(input_ids, dtype=torch.long),
            "attention_mask": torch.tensor(attention_masks, dtype=torch.long),
            "labels": torch.tensor(labels, dtype=torch.long),
        }
        supervised = batch["labels"].ne(-100)
        if not supervised.any():
            raise RuntimeError("batch에 assistant 학습 token이 없습니다.")
        first_supervised = supervised.nonzero(as_tuple=False)[:, 1].min().item()
        # Keep the logit immediately before the first supervised token through
        # the end.  That preceding logit predicts the first assistant token.
        batch["logits_to_keep"] = max_length - first_supervised + 1
        return batch

    return collate


def ensure_output_is_safe(args: argparse.Namespace) -> None:
    output = args.output_dir
    if output.exists() and not output.is_dir():
        raise DataValidationError(f"출력 경로가 디렉터리가 아닙니다: {output}")
    if args.resume_from_checkpoint is not None and not args.resume_from_checkpoint.is_dir():
        raise DataValidationError(
            f"resume checkpoint 디렉터리를 찾을 수 없습니다: {args.resume_from_checkpoint}"
        )
    if (
        output.exists()
        and any(output.iterdir())
        and args.resume_from_checkpoint is None
        and not args.overwrite_output_dir
    ):
        raise DataValidationError(
            f"출력 디렉터리가 비어 있지 않습니다: {output}. "
            "이어하려면 --resume-from-checkpoint, 덮어쓰기를 허용하려면 --overwrite-output-dir를 사용하세요."
        )


def atomic_write_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp")
    temporary.write_text(
        json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    os.replace(temporary, path)


def atomic_write_jsonl(path: Path, values: Sequence[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp")
    with temporary.open("w", encoding="utf-8") as target:
        for value in values:
            target.write(
                json.dumps(value, ensure_ascii=False, separators=(",", ":")) + "\n"
            )
        target.flush()
        os.fsync(target.fileno())
    os.replace(temporary, path)


def rename_metric_prefix(
    metrics: dict[str, float | int], old_prefix: str, new_prefix: str
) -> dict[str, float | int]:
    return {
        (
            new_prefix + key[len(old_prefix) :]
            if key.startswith(old_prefix)
            else key
        ): value
        for key, value in metrics.items()
    }


def run_training(
    args: argparse.Namespace,
    data_path: Path,
    train_records: list[TrainingRecord],
    evaluation_records: list[TrainingRecord],
    split_metadata: dict[str, Any],
    *,
    evaluation_role: str = "test",
) -> dict[str, Any]:
    stack = import_training_stack()
    torch = stack["torch"]
    if not torch.cuda.is_available():
        raise RuntimeError("Qwen3-4B 추가학습에는 CUDA GPU가 필요합니다.")

    local_rank = int(os.environ.get("LOCAL_RANK", args.local_rank if args.local_rank >= 0 else 0))
    rank = int(os.environ.get("RANK", "0"))
    world_size = int(os.environ.get("WORLD_SIZE", "1"))
    if local_rank >= torch.cuda.device_count():
        raise RuntimeError(
            f"LOCAL_RANK={local_rank}이지만 사용 가능한 GPU는 {torch.cuda.device_count()}개입니다."
        )
    torch.cuda.set_device(local_rank)
    stack["set_seed"](args.seed)
    if rank != 0:
        # Seven identical model-loading progress bars and third-party
        # deprecation warnings make tee'd tmux logs needlessly unreadable.
        stack["transformers_logging"].disable_progress_bar()
        stack["transformers_logging"].set_verbosity_error()
        warnings.filterwarnings(
            "ignore", category=FutureWarning, module=r"bitsandbytes(?:\..*)?"
        )
        warnings.filterwarnings(
            "ignore",
            category=FutureWarning,
            message=r"`torch\.distributed\.all_gather_into_tensor` is deprecated.*",
        )

    dtype_argument = (
        "dtype" if parse_version(stack["transformers_version"]) >= (5,) else "torch_dtype"
    )
    model_kwargs: dict[str, Any] = {
        "revision": args.revision,
        dtype_argument: torch.float16,
        "device_map": {"": local_rank},
        "low_cpu_mem_usage": True,
    }
    if args.attn_implementation:
        model_kwargs["attn_implementation"] = args.attn_implementation
    if args.use_4bit:
        model_kwargs["quantization_config"] = stack["BitsAndBytesConfig"](
            load_in_4bit=True,
            bnb_4bit_quant_type="nf4",
            bnb_4bit_compute_dtype=torch.float16,
            bnb_4bit_use_double_quant=True,
        )

    tokenizer = stack["AutoTokenizer"].from_pretrained(
        args.model, revision=args.revision, use_fast=True
    )
    if tokenizer.pad_token_id is None:
        tokenizer.pad_token = tokenizer.eos_token
    tokenizer.padding_side = "right"

    if rank == 0:
        print(f"[model] {args.model} (revision={args.revision})", file=sys.stderr)
        print(f"[device] GPU {local_rank}, world_size={world_size}, fp16", file=sys.stderr)
    model = stack["AutoModelForCausalLM"].from_pretrained(args.model, **model_kwargs)
    model.config.use_cache = False
    if "logits_to_keep" not in inspect.signature(model.forward).parameters:
        raise RuntimeError(
            "현재 모델 forward가 logits_to_keep를 지원하지 않습니다. "
            "Qwen3 및 transformers>=4.51 조합인지 확인하세요."
        )
    model.loss_function = make_chunked_causal_lm_loss(torch, args.loss_chunk_size)
    if args.use_4bit:
        model = stack["prepare_model_for_kbit_training"](
            model,
            use_gradient_checkpointing=args.gradient_checkpointing,
            gradient_checkpointing_kwargs={"use_reentrant": False},
        )
    elif args.gradient_checkpointing:
        model.gradient_checkpointing_enable(gradient_checkpointing_kwargs={"use_reentrant": False})
        model.enable_input_require_grads()

    lora_config = stack["LoraConfig"](
        r=args.lora_rank,
        lora_alpha=args.lora_alpha,
        lora_dropout=args.lora_dropout,
        bias="none",
        task_type="CAUSAL_LM",
        target_modules=LORA_TARGET_MODULES,
    )
    model = stack["get_peft_model"](model, lora_config)
    if rank == 0:
        model.print_trainable_parameters()
        print(
            f"[memory] attention={args.attn_implementation}, "
            f"assistant-only logits, loss chunk={args.loss_chunk_size} tokens",
            file=sys.stderr,
        )

    encoded_train, train_lengths = encode_records(
        train_records, tokenizer, args.max_seq_length
    )
    encoded_evaluation, evaluation_lengths = encode_records(
        evaluation_records, tokenizer, args.max_seq_length
    )
    if rank == 0:
        all_lengths = train_lengths + evaluation_lengths
        print(
            f"[tokens] min={min(all_lengths)}, p50={percentile(all_lengths, 0.50)}, "
            f"p95={percentile(all_lengths, 0.95)}, max={max(all_lengths)}",
            file=sys.stderr,
        )

    samples_per_process = math.ceil(len(train_records) / world_size)
    batches_per_process = math.ceil(samples_per_process / args.batch_size)
    updates_per_epoch = max(
        1, math.ceil(batches_per_process / args.gradient_accumulation_steps)
    )
    total_training_steps = math.ceil(updates_per_epoch * args.epochs)
    warmup_steps = math.ceil(total_training_steps * args.warmup_ratio)
    if rank == 0:
        print(
            f"[train] optimizer steps={total_training_steps:,} "
            f"({updates_per_epoch:,}/epoch) · warmup steps={warmup_steps:,}",
            file=sys.stderr,
        )

    training_argument_names = inspect.signature(stack["TrainingArguments"]).parameters
    compatibility_args: dict[str, Any] = {}
    if "overwrite_output_dir" in training_argument_names:
        compatibility_args["overwrite_output_dir"] = args.overwrite_output_dir
    if "save_safetensors" in training_argument_names:
        compatibility_args["save_safetensors"] = True

    training_args = stack["TrainingArguments"](
        output_dir=str(args.output_dir),
        num_train_epochs=args.epochs,
        per_device_train_batch_size=args.batch_size,
        per_device_eval_batch_size=args.test_batch_size,
        gradient_accumulation_steps=args.gradient_accumulation_steps,
        learning_rate=args.learning_rate,
        lr_scheduler_type="cosine",
        warmup_steps=warmup_steps,
        weight_decay=args.weight_decay,
        max_grad_norm=0.3,
        fp16=True,
        bf16=False,
        gradient_checkpointing=args.gradient_checkpointing,
        gradient_checkpointing_kwargs={"use_reentrant": False},
        optim="paged_adamw_8bit" if args.use_4bit else "adamw_torch_fused",
        logging_strategy="steps",
        logging_steps=args.logging_steps,
        logging_first_step=True,
        eval_strategy="no",
        save_strategy="epoch",
        save_total_limit=args.save_total_limit,
        load_best_model_at_end=False,
        prediction_loss_only=True,
        report_to="none",
        seed=args.seed,
        data_seed=args.seed,
        dataloader_num_workers=args.dataloader_num_workers,
        ddp_find_unused_parameters=False if world_size > 1 else None,
        remove_unused_columns=False,
        **compatibility_args,
    )
    data_collator = make_collator(torch, tokenizer.pad_token_id)
    trainer = stack["Trainer"](
        model=model,
        args=training_args,
        train_dataset=EncodedDataset(encoded_train),
        data_collator=data_collator,
        processing_class=tokenizer,
    )
    result = trainer.train(
        resume_from_checkpoint=(
            str(args.resume_from_checkpoint) if args.resume_from_checkpoint is not None else None
        )
    )
    # Evaluation records are never passed to Trainer and cannot affect updates.
    gc.collect()
    torch.cuda.empty_cache()
    evaluation_model = trainer.accelerator.unwrap_model(trainer.model_wrapped)
    teacher_forced_raw = evaluate_test_metrics(
        torch=torch,
        model=evaluation_model,
        encoded_test=encoded_evaluation,
        data_collator=data_collator,
        device=torch.device("cuda", local_rank),
        rank=rank,
        world_size=world_size,
        batch_size=args.test_batch_size,
    )
    teacher_forced_metrics = rename_metric_prefix(
        teacher_forced_raw, "test_", f"{evaluation_role}_"
    )
    evaluation_metrics: dict[str, float | int] = dict(teacher_forced_metrics)
    generation_predictions: list[dict[str, Any]] = []
    if args.generation_eval:
        generation_raw, generation_predictions = evaluate_generation_metrics(
            torch=torch,
            model=evaluation_model,
            tokenizer=tokenizer,
            records=evaluation_records,
            system_prompt=SYSTEM_PROMPT,
            device=torch.device("cuda", local_rank),
            rank=rank,
            world_size=world_size,
            batch_size=args.generation_batch_size,
            max_new_tokens=args.generation_max_new_tokens,
        )
        evaluation_metrics.update(
            {
                f"{evaluation_role}_{key}": value
                for key, value in generation_raw.items()
            }
        )
    trainer.log(evaluation_metrics)
    if trainer.is_world_process_zero():
        print(
            f"[{evaluation_role}] loss="
            f"{evaluation_metrics[f'{evaluation_role}_loss']:.6f} · "
            f"accuracy={evaluation_metrics[f'{evaluation_role}_accuracy']:.2%} · "
            f"teacher-forced exact="
            f"{evaluation_metrics[f'{evaluation_role}_teacher_forced_exact_match']:.2%} · "
            f"tokens={evaluation_metrics[f'{evaluation_role}_correct_tokens']:,}/"
            f"{evaluation_metrics[f'{evaluation_role}_supervised_tokens']:,} · "
            f"exact={evaluation_metrics[f'{evaluation_role}_exact_match_count']:,}/"
            f"{evaluation_metrics[f'{evaluation_role}_samples']:,} · "
            f"runtime={evaluation_metrics.get(f'{evaluation_role}_runtime', float('nan')):.2f}s",
            file=sys.stderr,
        )
        if args.generation_eval:
            print(
                f"[{evaluation_role}-generation] valid="
                f"{evaluation_metrics[f'{evaluation_role}_generation_valid_rate']:.2%} · "
                f"strict="
                f"{evaluation_metrics[f'{evaluation_role}_generation_strict_exact_match']:.2%} · "
                f"order-insensitive="
                f"{evaluation_metrics[f'{evaluation_role}_generation_order_insensitive_exact_match']:.2%} · "
                f"normalized="
                f"{evaluation_metrics[f'{evaluation_role}_generation_normalized_exact_match']:.2%}",
                file=sys.stderr,
            )
    trainer.save_model(str(args.output_dir))
    trainer.save_state()

    training_metrics = dict(result.metrics)
    resolved_revision = getattr(model.config, "_commit_hash", None) or args.revision
    manifest: dict[str, Any] = {
        "base_model": args.model,
        "requested_revision": args.revision,
        "resolved_revision": resolved_revision,
        "data_path": str(data_path),
        "data_sha256": sha256_file(data_path),
        "record_count": len(train_records) + len(evaluation_records),
        "train_count": len(train_records),
        f"{evaluation_role}_count": len(evaluation_records),
        "train_cve_ids": [record.cve_id for record in train_records],
        f"{evaluation_role}_cve_ids": [
            record.cve_id for record in evaluation_records
        ],
        "evaluation_role": evaluation_role,
        "split": split_metadata,
        "system_prompt": SYSTEM_PROMPT,
        "target_shape": {"bindings": "list[binding]"},
        "lora_target_modules": LORA_TARGET_MODULES,
        "cli_args": {
            key: str(value) if isinstance(value, Path) else value
            for key, value in vars(args).items()
        },
        "training_metrics": training_metrics,
        f"{evaluation_role}_metrics": evaluation_metrics,
        "metric_definitions": {
            "accuracy": "micro next-token accuracy over gold assistant JSON tokens",
            "teacher_forced_exact_match": (
                "fraction of records whose complete assistant answer is token-perfect "
                "while conditioning on the gold prefix"
            ),
            "generation_strict_exact_match": (
                "greedy free-generation payload equals the labeled JSON structure"
            ),
            "generation_order_insensitive_exact_match": (
                "free-generation exact match after sorting bindings and version ranges"
            ),
            "generation_normalized_exact_match": (
                "order-insensitive free-generation exact match after case/punctuation "
                "normalization of string fields"
            ),
            "aggregation": (
                "each DDP rank evaluates a unique unpadded shard; scalar counts are summed"
            ),
        },
        "packages": {
            name: package_version(name)
            for name in ["torch", "transformers", "accelerate", "peft", "bitsandbytes"]
        },
    }
    if trainer.is_world_process_zero():
        tokenizer.save_pretrained(args.output_dir)
        atomic_write_json(args.output_dir / "training_manifest.json", manifest)
        if args.generation_eval:
            atomic_write_jsonl(
                args.output_dir / f"{evaluation_role}_predictions.jsonl",
                generation_predictions,
            )
        print(f"완료: LoRA adapter와 tokenizer를 저장했습니다: {args.output_dir}")

    if torch.distributed.is_available() and torch.distributed.is_initialized():
        torch.distributed.barrier(device_ids=[local_rank])
    if hasattr(trainer.accelerator, "free_memory"):
        trainer.accelerator.free_memory()
    del evaluation_model, trainer, model, tokenizer, data_collator
    gc.collect()
    torch.cuda.empty_cache()
    return {
        "training_metrics": training_metrics,
        "evaluation_metrics": evaluation_metrics,
        "manifest": manifest,
    }


def metric_summary(values: Sequence[float]) -> dict[str, float]:
    mean = sum(values) / len(values)
    variance = sum((value - mean) ** 2 for value in values) / len(values)
    return {
        "mean": mean,
        "std": math.sqrt(variance),
        "min": min(values),
        "max": max(values),
    }


def aggregate_cv_metrics(
    fold_results: Sequence[dict[str, Any]],
) -> dict[str, Any]:
    metrics = [result["evaluation_metrics"] for result in fold_results]
    keys = sorted(
        {
            key
            for fold_metrics in metrics
            for key, value in fold_metrics.items()
            if isinstance(value, (int, float))
            and not isinstance(value, bool)
            and (
                key.endswith("_rate")
                or key.endswith("_match")
                or key.endswith("_accuracy")
                or key.endswith("_loss")
            )
        }
    )
    macro = {
        key: metric_summary([float(fold_metrics[key]) for fold_metrics in metrics])
        for key in keys
        if all(key in fold_metrics for fold_metrics in metrics)
    }
    supervised_tokens = sum(
        int(item["validation_supervised_tokens"]) for item in metrics
    )
    validation_samples = sum(int(item["validation_samples"]) for item in metrics)
    micro: dict[str, float | int] = {
        "validation_samples": validation_samples,
        "validation_supervised_tokens": supervised_tokens,
        "validation_loss": sum(
            float(item["validation_loss"])
            * int(item["validation_supervised_tokens"])
            for item in metrics
        )
        / supervised_tokens,
        "validation_accuracy": sum(
            int(item["validation_correct_tokens"]) for item in metrics
        )
        / supervised_tokens,
        "validation_teacher_forced_exact_match": sum(
            int(item["validation_exact_match_count"]) for item in metrics
        )
        / validation_samples,
    }
    if all("validation_generation_samples" in item for item in metrics):
        generation_samples = sum(
            int(item["validation_generation_samples"]) for item in metrics
        )
        micro.update(
            {
                "validation_generation_samples": generation_samples,
                "validation_generation_valid_rate": sum(
                    int(item["validation_generation_valid_count"])
                    for item in metrics
                )
                / generation_samples,
                "validation_generation_strict_exact_match": sum(
                    int(item["validation_generation_strict_exact_count"])
                    for item in metrics
                )
                / generation_samples,
                "validation_generation_order_insensitive_exact_match": sum(
                    int(
                        item[
                            "validation_generation_order_insensitive_exact_count"
                        ]
                    )
                    for item in metrics
                )
                / generation_samples,
                "validation_generation_normalized_exact_match": sum(
                    int(item["validation_generation_normalized_exact_count"])
                    for item in metrics
                )
                / generation_samples,
            }
        )
    return {"macro_fold_statistics": macro, "micro_oof": micro}


def run_cross_validation(
    *,
    args: argparse.Namespace,
    data_path: Path,
    development_records: list[TrainingRecord],
    locked_test_records: list[TrainingRecord],
    outer_split_metadata: dict[str, Any],
    folds: Sequence[CVFold],
    cv_metadata: dict[str, Any],
) -> None:
    if args.resume_from_checkpoint is not None:
        raise DataValidationError(
            "--resume-from-checkpoint는 단일 학습에서만 지원됩니다. "
            "CV 재실행은 새 output-dir를 사용하세요."
        )
    root_output = args.output_dir.resolve()
    fold_results: list[dict[str, Any]] = []
    rank = int(os.environ.get("RANK", "0"))
    for fold in folds:
        fold_args = argparse.Namespace(**vars(args))
        fold_args.output_dir = root_output / f"fold-{fold.index:02d}"
        fold_args.seed = args.seed + fold.index
        fold_args.resume_from_checkpoint = None
        ensure_output_is_safe(fold_args)
        if rank == 0:
            print(
                f"[cv] fold {fold.index}/{len(folds)} · "
                f"train {len(fold.train_records):,} / "
                f"validation {len(fold.validation_records):,} · "
                f"output={fold_args.output_dir}",
                file=sys.stderr,
            )
        result = run_training(
            fold_args,
            data_path,
            list(fold.train_records),
            list(fold.validation_records),
            {
                "outer_split": outer_split_metadata,
                "cross_validation": cv_metadata,
                "fold": fold.metadata,
                "locked_test_evaluated": False,
            },
            evaluation_role="validation",
        )
        fold_results.append(result)

    if rank == 0:
        aggregate = aggregate_cv_metrics(fold_results)
        fold_summaries = [
            {
                "fold_index": fold.index,
                "output_dir": str((root_output / f"fold-{fold.index:02d}").resolve()),
                "train_count": len(fold.train_records),
                "validation_count": len(fold.validation_records),
                "training_metrics": result["training_metrics"],
                "validation_metrics": result["evaluation_metrics"],
            }
            for fold, result in zip(folds, fold_results)
        ]
        cv_manifest = {
            "mode": "stratified_product_group_cross_validation",
            "base_model": args.model,
            "requested_revision": args.revision,
            "data_path": str(data_path),
            "data_sha256": sha256_file(data_path),
            "record_count": len(development_records) + len(locked_test_records),
            "development_count": len(development_records),
            "locked_test_count": len(locked_test_records),
            "locked_test_evaluated": False,
            "development_cve_ids": [
                record.cve_id for record in development_records
            ],
            "locked_test_cve_ids": [
                record.cve_id for record in locked_test_records
            ],
            "outer_split": outer_split_metadata,
            "cross_validation": cv_metadata,
            "folds": fold_summaries,
            "aggregate_metrics": aggregate,
            "system_prompt": SYSTEM_PROMPT,
            "cli_args": {
                key: str(value) if isinstance(value, Path) else value
                for key, value in vars(args).items()
            },
        }
        atomic_write_json(root_output / "cv_manifest.json", cv_manifest)
        if args.generation_eval:
            oof_predictions: list[dict[str, Any]] = []
            for fold in folds:
                prediction_path = (
                    root_output
                    / f"fold-{fold.index:02d}"
                    / "validation_predictions.jsonl"
                )
                with prediction_path.open("r", encoding="utf-8") as source:
                    for line in source:
                        prediction = json.loads(line)
                        prediction["fold_index"] = fold.index
                        oof_predictions.append(prediction)
            oof_predictions.sort(key=lambda item: item["cve_id"])
            if len(oof_predictions) != len(development_records) or len(
                {item["cve_id"] for item in oof_predictions}
            ) != len(development_records):
                raise RuntimeError("OOF prediction에 development 레코드 누락/중복이 있습니다.")
            atomic_write_jsonl(
                root_output / "oof_predictions.jsonl", oof_predictions
            )
        micro = aggregate["micro_oof"]
        message = (
            f"[cv-summary] teacher-forced exact="
            f"{micro['validation_teacher_forced_exact_match']:.2%}"
        )
        if "validation_generation_normalized_exact_match" in micro:
            message += (
                " · generation normalized exact="
                f"{micro['validation_generation_normalized_exact_match']:.2%}"
            )
        print(message, file=sys.stderr)
        print(
            f"완료: {len(folds)}-fold CV 결과를 저장했습니다: {root_output} "
            "(locked test는 평가하지 않음)"
        )


