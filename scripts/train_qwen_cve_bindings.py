def validate_cli_args(args: argparse.Namespace) -> None:
    positive_values = {
        "--max-seq-length": args.max_seq_length,
        "--epochs": args.epochs,
        "--batch-size": args.batch_size,
        "--test-batch-size": args.test_batch_size,
        "--generation-batch-size": args.generation_batch_size,
        "--generation-max-new-tokens": args.generation_max_new_tokens,
        "--gradient-accumulation-steps": args.gradient_accumulation_steps,
        "--learning-rate": args.learning_rate,
        "--lora-rank": args.lora_rank,
        "--lora-alpha": args.lora_alpha,
        "--logging-steps": args.logging_steps,
        "--save-total-limit": args.save_total_limit,
        "--loss-chunk-size": args.loss_chunk_size,
    }
    invalid = [name for name, value in positive_values.items() if value <= 0]
    if invalid:
        raise DataValidationError(f"0보다 커야 하는 인자: {', '.join(invalid)}")
    if any(value <= 0 for value in args.split_ratio):
        raise DataValidationError("--split-ratio의 두 값은 모두 0보다 커야 합니다.")
    if args.cv_folds < 1:
        raise DataValidationError("--cv-folds는 1 이상이어야 합니다.")
    if not 0.0 <= args.warmup_ratio < 1.0:
        raise DataValidationError("--warmup-ratio는 0 이상 1 미만이어야 합니다.")
    if not 0.0 <= args.lora_dropout < 1.0:
        raise DataValidationError("--lora-dropout은 0 이상 1 미만이어야 합니다.")


def cleanup_distributed_after_failure() -> None:
    """Release NCCL state when training exits before its normal synchronization."""
    torch = sys.modules.get("torch")
    distributed = getattr(torch, "distributed", None) if torch is not None else None
    if (
        distributed is not None
        and distributed.is_available()
        and distributed.is_initialized()
    ):
        try:
            # Do not barrier here: another rank may already have failed or been
            # terminated by torchrun, which would turn cleanup into a hang.
            distributed.destroy_process_group()
        except RuntimeError:
            pass


def main() -> int:
    args = parse_args()
    try:
        validate_cli_args(args)
        data_path = args.data.resolve()
        records = load_records(data_path)
        empty_count = sum(not record.bindings for record in records)
        rank = int(os.environ.get("RANK", "0"))
        if args.cv_folds > 1:
            development_records, locked_test_records, outer_metadata = (
                split_development_test_grouped(
                    records, tuple(args.split_ratio), args.seed
                )
            )
            folds, cv_metadata = make_cv_folds(
                development_records, args.cv_folds, args.seed
            )
            if rank == 0:
                fold_counts = ", ".join(
                    f"{fold.index}:{len(fold.train_records)}/"
                    f"{len(fold.validation_records)}"
                    for fold in folds
                )
                print(
                    f"[data] 전체 {len(records):,}건 (빈 binding {empty_count:,}건) · "
                    f"development {len(development_records):,} / "
                    f"locked test {len(locked_test_records):,} · "
                    f"{args.cv_folds}-fold train/validation={fold_counts} · "
                    f"seed {args.seed}",
                    file=sys.stderr,
                )
            if args.validate_only:
                if rank == 0:
                    print(
                        "검증 완료: JSONL 스키마, grouped 9:1 split, "
                        f"{args.cv_folds}-fold Stratified Group CV가 정상입니다."
                    )
                return 0
            ensure_output_is_safe(args)
            run_cross_validation(
                args=args,
                data_path=data_path,
                development_records=development_records,
                locked_test_records=locked_test_records,
                outer_split_metadata=outer_metadata,
                folds=folds,
                cv_metadata=cv_metadata,
            )
        else:
            train_records, test_records, split_metadata = split_train_test(
                records, tuple(args.split_ratio), args.seed
            )
            if rank == 0:
                print(
                    f"[data] 전체 {len(records):,}건 (빈 binding {empty_count:,}건) · "
                    f"train {len(train_records):,} / test {len(test_records):,} · "
                    f"ratio {args.split_ratio[0]}:{args.split_ratio[1]} · "
                    f"seed {args.seed}",
                    file=sys.stderr,
                )
            if args.validate_only:
                if rank == 0:
                    print(
                        "검증 완료: JSONL 스키마, CVE ID 중복, "
                        "train/test split이 정상입니다."
                    )
                return 0
            ensure_output_is_safe(args)
            run_training(
                args,
                data_path,
                train_records,
                test_records,
                split_metadata,
                evaluation_role="test",
            )
    except (DataValidationError, OSError, RuntimeError, ValueError) as exc:
        print(f"오류: {exc}", file=sys.stderr)
        return 1
    finally:
        cleanup_distributed_after_failure()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
